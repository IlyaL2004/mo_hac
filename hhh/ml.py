    def _detect_file_type(self, file_path):
        """Определяет тип файла и его структуру"""
        ext = os.path.splitext(file_path)[1].lower()

        if ext in ['.xlsx', '.xls', '.csv']:
            return 'structured'
        elif ext in ['.txt', '.doc', '.docx', '.pdf']:
            return 'text'
        else:
            return 'unknown'

    def _extract_from_text(self, file_path):
        """Извлекает информацию из текстового файла"""
        try:
            # Чтение текстового файла
            if file_path.endswith('.txt'):
                with open(file_path, 'r', encoding='utf-8') as f:
                    content = f.read()
            elif file_path.endswith('.pdf'):
                # Для PDF потребуется дополнительная библиотека
                try:
                    import PyPDF2
                    with open(file_path, 'rb') as f:
                        reader = PyPDF2.PdfReader(f)
                        content = ''
                        for page in reader.pages:
                            content += page.extract_text()
                except ImportError:
                    return self._fallback_text_extraction(file_path)
            else:
                return self._fallback_text_extraction(file_path)

            return self._parse_text_content(content)

        except Exception as e:
            print(f"❌ Ошибка чтения текстового файла: {e}")
            return [self._create_empty_row()]

    def _fallback_text_extraction(self, file_path):
        """Резервный метод для текстовых файлов"""
        try:
            # Пытаемся прочитать как текстовый файл
            with open(file_path, 'r', encoding='utf-8', errors='ignore') as f:
                content = f.read()
            return self._parse_text_content(content)
        except:
            return [self._create_empty_row()]

    def _parse_text_content(self, content):
        """Парсит текстовый контент и извлекает информацию"""
        extracted_data = {col: "не найдено" for col in self.target_columns}

        # Поиск по ключевым словам
        for field, patterns in self.keyword_patterns.items():
            for pattern in patterns:
                matches = re.findall(pattern, content, re.IGNORECASE | re.DOTALL)
                if matches:
                    extracted_data[field] = matches[0]
                    break

        # Семантический поиск дополнительной информации
        extracted_data.update(self._semantic_text_search(content))

        return [extracted_data]

    def _semantic_text_search(self, content):
        """Семантический поиск информации в тексте"""
        results = {}

        # Разбиваем текст на предложения
        sentences = re.split(r'[.!?]+', content)
        sentences = [s.strip() for s in sentences if len(s.strip()) > 10]

        if not sentences:
            return results

        # Кодируем предложения
        sentence_embeddings = self.model.encode(sentences, convert_to_tensor=True)

        # Для каждой целевой колонки ищем наиболее релевантное предложение
        for i, target_col in enumerate(self.target_columns):
            if target_col in results:  # Уже нашли через regex
                continue

            target_embedding = self.target_embeddings[i].unsqueeze(0)
            similarities = cosine_similarity(
                target_embedding.cpu().numpy(),
                sentence_embeddings.cpu().numpy()
            )[0]

            best_match_idx = np.argmax(similarities)
            best_similarity = similarities[best_match_idx]

            if best_similarity > 0.7:  # Высокий порог для текста
                results[target_col] = sentences[best_match_idx]

        return results

    def _process_structured_file(self, file_path):
        """Обрабатывает структурированные файлы (Excel, CSV)"""
        try:
            if file_path.endswith(('.xlsx', '.xls')):
                df = pd.read_excel(file_path)
            elif file_path.endswith('.csv'):
                try:
                    df = pd.read_csv(file_path, encoding='utf-8')
                except UnicodeDecodeError:
                    df = pd.read_csv(file_path, encoding='cp1251')
            else:
                raise ValueError(f"Неподдерживаемый формат: {file_path}")

            print(f"   📊 Загружено: {len(df.columns)} колонок, {len(df)} строк")

            # Сопоставляем колонки
            column_mapping = {}
            for source_col in df.columns:
                source_norm = self._normalize_text(source_col)
                source_embedding = self.model.encode([source_norm], convert_to_tensor=True)

                similarities = cosine_similarity(
                    source_embedding.cpu().numpy(),
                    self.target_embeddings.cpu().numpy()
                )[0]

                best_idx = np.argmax(similarities)
                best_similarity = similarities[best_idx]

                if best_similarity > 0.6:
                    target_col = self.target_columns[best_idx]
                    column_mapping[source_col] = target_col
                    print(f"   ✅ {source_col} -> {target_col} ({best_similarity:.3f})")
                else:
                    print(f"   ❌ {source_col} -> не найдено ({best_similarity:.3f})")

            # Создаем результат
            result_data = []
            for idx in range(len(df)):
                row = {col: "не найдено" for col in self.target_columns}

                for source_col, target_col in column_mapping.items():
                    value = df.iloc[idx][source_col]
                    if pd.notna(value) and str(value).strip():
                        row[target_col] = value

                result_data.append(row)

            return result_data

        except Exception as e:
            print(f"❌ Ошибка обработки структурированного файла: {e}")
            return [self._create_empty_row()]

    def _create_empty_row(self):
        """Создает пустую строку с эталонной схемой"""
        return {col: "не найдено" for col in self.target_columns}

    def process_single_file(self, file_path):
        """Обрабатывает один файл и возвращает DataFrame с эталонной схемой"""
        print(f"\n📁 Обработка: {file_path}")

        file_type = self._detect_file_type(file_path)

        if file_type == 'structured':
            result_data = self._process_structured_file(file_path)
        elif file_type == 'text':
            result_data = self._extract_from_text(file_path)
        else:
            print(f"❌ Неподдерживаемый формат файла: {file_path}")
            result_data = [self._create_empty_row()]

        result_df = pd.DataFrame(result_data, columns=self.target_columns)

        # Статистика
        filled_columns = sum(1 for col in result_df.columns
                             if not all(result_df[col] == "не найдено"))
        print(f"📊 Результат: заполнено {filled_columns}/{len(self.target_columns)} колонок")

        return result_df

    def process_multiple_files(self, file_paths):
        """
        Обрабатывает несколько файлов и возвращает объединенный DataFrame

        Args:
            file_paths (list): Список путей к файлам

        Returns:
            pd.DataFrame: Объединенный DataFrame с эталонной схемой
        """
        all_results = []

        for file_path in file_paths:
            try:
                result_df = self.process_single_file(file_path)
                all_results.append(result_df)
                print(f"Успешно обработан: {file_path}")
            except Exception as e:
                print(f"Ошибка при обработке {file_path}: {str(e)}")
                continue

        if not all_results:
            raise Exception("Не удалось обработать ни один файл")

        print(f"\n Объединение {len(all_results)} файлов...")
        final_df = pd.concat(all_results, ignore_index=True, ignore_columns=False)

        print(f" Финальный результат: {len(final_df)} строк × {len(final_df.columns)} колонок")
        return final_df

    def save_result(self, dataframe, output_path):
        """
        Сохраняет результат в Excel файл

        Args:
            dataframe (pd.DataFrame): DataFrame для сохранения
            output_path (str): Путь для сохранения
        """
        dataframe.to_excel(output_path, index=False)
        print(f" Результат сохранен: {output_path}")

